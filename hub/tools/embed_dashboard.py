# PlatformIO pre-build script (also runnable by hand: python3 tools/embed_dashboard.py <hub dir>).
# Gzips web/dashboard.html into src/gen/dashboard_gz.h. Only rewrites the header when the content changes,
# so unchanged dashboards do not force web.cpp to recompile.
import gzip, os, sys

def generate(proj):
    src = os.path.join(proj, "web", "dashboard.html")
    out_dir = os.path.join(proj, "src", "gen")
    out = os.path.join(out_dir, "dashboard_gz.h")
    os.makedirs(out_dir, exist_ok=True)
    gz = gzip.compress(open(src, "rb").read(), compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(gz), 16):
        lines.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]))
    text = ("// Generated by tools/embed_dashboard.py from web/dashboard.html. Do not edit.\n#pragma once\n#include <Arduino.h>\n"
            "const size_t dashboard_gz_len = %d;\nconst uint8_t dashboard_gz[] PROGMEM = {\n%s\n};\n" % (len(gz), ",\n".join(lines)))
    if not os.path.exists(out) or open(out).read() != text:
        open(out, "w").write(text)
    print("dashboard embedded: %d bytes gzipped" % len(gz))

try:
    Import("env")  # noqa: F821  (SCons: provided by PlatformIO)
    generate(env["PROJECT_DIR"])  # noqa: F821
except NameError:
    generate(sys.argv[1] if len(sys.argv) > 1 else ".")
